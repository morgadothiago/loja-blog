export const dictionaries: Record<Locale, Messages> = { "pt-BR": ptBR, en, es };

export function isLocale(value: unknown): value is Locale {
  return LOCALES.includes(value as Locale);
}

// Mensagem do usuário para um erro do contrato Result: o detalhe específico vence o código geral.
export function translateError(
  t: (key: MessageKey) => string,
  error: { code: string; detailCode?: string },
): string {
  const specific = `error.${error.detailCode}` as MessageKey;
  if (error.detailCode && specific in dictionaries["pt-BR"]) return t(specific);
  const general = `error.${error.code}` as MessageKey;
  return general in dictionaries["pt-BR"] ? t(general) : t("error.INTERNAL");
}

export function translateFieldError(t: (key: MessageKey) => string, code: string | undefined): string | undefined {
  if (!code) return undefined;
  const key = `error.field.${code}` as MessageKey;
  return key in dictionaries["pt-BR"] ? t(key) : t("error.field.INVALID");
}
